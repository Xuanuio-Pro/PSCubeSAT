#!/usr/bin/env bash
# Install and operate CubeSAT LMS on one machine (Linux/macOS; only Docker is required).
# Usage: bash setup-local.sh [install|start|stop|status|logs|admin] [--port N] [--skip-compiler]
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")"

action=install
port=8080
skip_compiler=false
while [[ $# -gt 0 ]]; do
  case "$1" in
    install|start|stop|status|logs|admin) action="$1" ;;
    --port) port="$2"; shift ;;
    --skip-compiler) skip_compiler=true ;;
    *) echo "Unknown argument: $1" >&2; exit 2 ;;
  esac
  shift
done

env_file="$PWD/.env.local"
compose=(docker compose --env-file "$env_file" -f docker-compose.local.yml)

docker info >/dev/null 2>&1 || { echo 'Docker is not running. Start Docker and run this again.' >&2; exit 1; }

if [[ ! -f "$env_file" ]]; then
  # Secrets are generated once and kept with the database volume; never commit this file.
  secret() { od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }
  umask 077
  cat > "$env_file" <<EOF
# Generated by setup-local.sh. Keep it with the data; do not commit it.
POSTGRES_PASSWORD=$(secret 24)
JWT_SECRET=$(secret 32)
LOCAL_PORT=$port
COMPILER_IMAGE=pscubesat-compiler:1
LMS_CLASS_MODE=false
EOF
  echo "Created .env.local (random secrets, port $port)."
fi
value() { grep -E "^$1=" "$env_file" | head -n1 | cut -d= -f2- || true; }
local_port="$(value LOCAL_PORT)"; local_port="${local_port:-8080}"
compiler_image="$(value COMPILER_IMAGE)"; compiler_image="${compiler_image:-pscubesat-compiler:1}"

case "$action" in
  stop) exec "${compose[@]}" stop ;;
  status) exec "${compose[@]}" ps -a ;;
  logs) exec "${compose[@]}" logs --tail 200 -f fastapi ;;
  admin) exec "${compose[@]}" exec fastapi python scripts/create_admin.py ;;
  start) "${compose[@]}" up -d --wait --wait-timeout 300 ;;
  install)
    echo 'Building and starting PostgreSQL, Redis, backend and frontend (first run 3-10 min)...'
    "${compose[@]}" up -d --build --wait --wait-timeout 300
    if ! docker image inspect "$compiler_image" >/dev/null 2>&1; then
      if [[ "$skip_compiler" == true ]]; then
        echo "WARNING: compiler image skipped; Compile fails until you rerun without --skip-compiler." >&2
      else
        echo "Building compiler image $compiler_image (ESP32 toolchains, ~6 GB, first run 15-40 min)..."
        docker build -f fastapi-backend/compiler/Dockerfile -t "$compiler_image" fastapi-backend
      fi
    fi
    admins="$("${compose[@]}" exec -T postgres psql -U cubesat -d cubesat -tAc "SELECT count(*) FROM users WHERE role = 'admin'" | tr -d '[:space:]')"
    if [[ "$admins" == 0 ]]; then
      if [[ -t 0 ]]; then
        echo 'No administrator yet. Enter the first admin account:'
        "${compose[@]}" exec fastapi python scripts/create_admin.py
      else
        echo 'WARNING: no administrator yet. Run: bash setup-local.sh admin' >&2
      fi
    fi
    ;;
esac
echo
echo "CubeSAT LMS is running: http://localhost:$local_port  (admin sign-in: http://localhost:$local_port/admin/login)"
echo 'USB flashing needs Chrome/Edge opened at localhost on this machine.'
