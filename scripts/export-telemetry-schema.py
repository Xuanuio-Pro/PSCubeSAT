"""Export the backend contract as JSON Schema and frontend TypeScript types."""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / 'fastapi-backend'))
from app.models.telemetry import TelemetryFrame

schema = TelemetryFrame.model_json_schema()
schema['required'] = list(schema['properties'])  # Wire packets always include all fields.


def ts_type(prop):
    if 'const' in prop:
        return json.dumps(prop['const'])
    if 'enum' in prop:
        return ' | '.join(json.dumps(value) for value in prop['enum'])
    if 'anyOf' in prop:
        return ' | '.join(ts_type(value) for value in prop['anyOf'])
    return {'string': 'string', 'integer': 'number', 'number': 'number',
            'boolean': 'boolean', 'null': 'null'}[prop['type']]


types = '// Generated by scripts/export-telemetry-schema.py; do not edit.\nexport interface TelemetryFrame {\n'
types += ''.join(f"  {key}: {ts_type(prop)};\n" for key, prop in schema['properties'].items())
types += '}\n'
outputs = {root / 'shared/telemetry.schema.json': json.dumps(schema, indent=2, ensure_ascii=False) + '\n',
           root / 'src/telemetry/frame.d.ts': types}
for path, content in outputs.items():
    if '--check' in sys.argv:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            raise SystemExit(f'Outdated telemetry contract: {path.name}')
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')
